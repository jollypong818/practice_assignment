"""실습 01 기본필수: 학습과 예측 두 문장을 연결합니다."""

# 선형회귀(Linear Regression) 모델을 사용하기 위해 불러온다. 
from sklearn.linear_model import LinearRegression

# X는 입력 데이터이다. 한 행이 한 사람을 의미하고, 각 사람의 공부 시간을 나타낸다.
# 머신러닝 모델의 입력 X는 2차원 형태여야 하므로 [1,2,3,4,5] 가 아니라 [[1],[2],...[5]]형태로 작성
# X는 한 행이 한 사람이고, 각 행의 숫자는 공부시간입니다. 그래서 [[1], [2], ...]입니다.
X = [[1], [2], [3], [4], [5]]
# y는 X에 대응하는 실제 정답(점수)이다.
# 1시간 공부 → 52점
# 2시간 공부 → 61점
# 3시간 공부 → 69점
# 4시간 공부 → 80점
# 5시간 공부 → 89점
y = [52, 61, 69, 80, 89]  # 같은 순서의 실제 점수
model = LinearRegression()  # 선을 맞추는 모델(선형회귀 모델)을 준비합니다. 아직 학습 전입니다.
# 완료 B01: model을 X, y로 학습하고, [[6]]의 예측을 prediction에 넣으세요.
# 힌트: fit에는 입력과 정답, predict에는 입력만 전달합니다.
# X(공부시간)를 입력하고 y(실제 점수)를 정답으로 주어 모델을 학습시킨다.
# 모델은 공부시간과 점수 사이의 관계를 가장 잘 나타내는 직선을 찾는다.
model.fit(X,y)

# 학습한 모델을 이용하여 6시간 공부했을 때의 점수를 예측한다.
# predict()의 입력도 X와 마찬가지로 2차원 형태로 전달한다.
prediction = model.predict([[6]])

# coef_에는 학습된 직선의 기울기가 저장된다.
# 즉 공부시간이 1시간 증가할 때 점수가 얼마나 증가하는지를 의미한다.
print("기울기:", round(model.coef_[0], 1))
# intercept_에는 학습된 직선의 절편이 저장된다.
# 선형회귀식 y = ax + b에서 b에 해당한다.
print("절편:", round(model.intercept_, 1))
# 학습된 직선에 공부시간 6시간을 넣어서 예측한 점수를 출력한다.
# predict()의 결과는 배열이므로 prediction[0]으로 첫 번째 값을 가져온다.
print("6시간 예측:", round(prediction[0], 1))
# 주의: 6시간은 학습 범위 1~5시간 밖입니다. 수식 확인용이며 실제 점수를 보장하지 않습니다.
