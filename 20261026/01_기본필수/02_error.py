"""실습 02 기본필수: 미리 제공된 예측으로 MAE와 RMSE를 계산합니다."""
'''
scikit-learn(sklearn) 은 머신러닝 모델을 만들고 평가할 때 사용하는 라이브러리이다. 
metrics 모듈에는 모델의 예측이 실제값과 얼마나 차이나는지 평가하는 함수들이 들어 있다.
mean_absolute_error : MAE(평균절대오차)를 계산하는 함수
root_mean_squared_error : RMSE(평균제곱근오차)를 계산하는 함수
'''
from sklearn.metrics import mean_absolute_error, root_mean_squared_error

#실제 측정된 소요시간. 모델의 예측이 얼마나 정확한지 판단하기 위한 정답 역할을 한다. 
actual = [100, 200, 300]     # 실제 소요시간, 단위 ms
# 실제값 : 100, 200, 300
# 예측값 : 120, 180, 360
# 차이   : +20, -20, +60
prediction = [120, 180, 360] # 모델이 예측했다고 가정한 값, 단위 ms, actual 과 같은 위치의 값끼리 비교한다.


# 완료 B02: 실제값과 예측값을 두 평가 함수에 넣으세요.
# 힌트: 두 함수 모두 (actual, prediction) 순서로 호출합니다.

# MAE(Mean Absolute Error, 평균절대오차)
# 실제값과 예측값의 차이를 구한 뒤, 음수/양수 방향은 무시하고 오차의 크기만 보기위해 절댓값을 취한다. 
# |100 - 120| = 20
# |200 - 180| = 20
# |300 - 360| = 60
#
# 그 값들의 평균을 계산한다.
# (20 + 20 + 60) / 3 = 33.33
#
# → "모델의 예측이 실제값에서 평균적으로 약 33.33ms 정도 벗어났다"라고 해석할 수 있다.
# 함수에는 (실제값, 예측값) 순서로 전달한다.
mae = mean_absolute_error(actual, prediction)

# RMSE (Root Mean Squared Error, 평균제곱근오차)
# 실제값과 예측값의 차이를 제곱한 뒤 평균을 구하고, 마지막에 제곱근(root)을 씌운 값이다. 
# (100 - 120)^2 = 400
# (200 - 180)^2 = 400
# (300 - 360)^2 = 3600
#
# 큰 오차는 제곱되면서 더 크게 반영된다.
# 따라서 MAE보다 '큰 실수(큰 오차)'에 더 민감한 평가 지표이다.
#
# → 예측값 하나가 실제값에서 크게 벗어났을 때 더 강한 패널티를 주고 싶을 때 유용하다.
rmse = root_mean_squared_error(actual, prediction)
# round(값, 2)는 소수점 둘째 자리까지 반올림한다.
# 계산된 MAE를 보기 좋게 출력한다.
print("MAE(ms):", round(mae, 2))
# 계산된 RMSE도 소수점 둘째 자리까지 출력한다.
print("RMSE(ms):", round(rmse, 2))
# MAE는 절댓값 20·20·60의 평균입니다. RMSE는 제곱 400·400·3600의 평균에 루트를 취합니다.
