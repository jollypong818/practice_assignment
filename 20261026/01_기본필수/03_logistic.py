"""실습 03 기본필수: 작은 정상 자료로 확률과 클래스를 확인합니다."""

# scikit-learn 머신러닝 라이브러리에서 LogisticRegression을 가져온다. 

# LogisticRegression(로지스틱회귀)은 데이터를 두 개 이상의 클래스로 분류할 때 사용하는 머신러닝 알고리즘이다. 

# 이 실습에서는 작업 복잡도를 보고 작업이 성공할지(0), 실패할지(1) 를 예측하는데 사용한다. 

# LinearRegression -> 실행시간처럼 연속적인 숫자를 예측
# LogisticRegression -> 성공/ 실패처럼 정해진 범주를 분류

# 이름에 Regression(회귀)이 들어가지만 주로 분류 문제에 사용한다. 
from sklearn.linear_model import LogisticRegression

# X는 머신러닝 모델에게 제공할 입력 데이터이다.
#
# 실제로 수행했던 작업들의 복잡도를 기록한 것이다.
#
# X[0] = [1] → 복잡도 1인 작업
# X[1] = [2] → 복잡도 2인 작업
# X[2] = [3] → 복잡도 3인 작업
# X[3] = [4] → 복잡도 4인 작업
# X[4] = [5] → 복잡도 5인 작업
# X[5] = [6] → 복잡도 6인 작업
#
# 총 6개의 작업 기록이 있고, 각 작업의 특징은 복잡도 1개이다.
#
# X를 2차원 리스트로 만드는 이유:
# scikit-learn은 입력을 [샘플 수, 특징 수] 형태로 받기 때문이다.
# 현재 X의 구조는 6행 × 1열이다.
X = [[1], [2], [3], [4], [5], [6]]

# y는 각 작업의 실제 결과, 즉 정답데이터이다. 
# 0 = 성공, 1 = 실패
# X[0] = [1] -> y[0] = 0 -> 복잡도 1인 작업은 성공
# X[1] = [2] → y[1] = 0 → 복잡도 2인 작업은 성공
# X[2] = [3] → y[2] = 0 → 복잡도 3인 작업은 성공
# X[3] = [4] → y[3] = 1 → 복잡도 4인 작업은 실패
# X[4] = [5] → y[4] = 1 → 복잡도 5인 작업은 실패
# X[5] = [6] → y[5] = 1 → 복잡도 6인 작업은 실패

# 모델은 이 정답을 참고하여 복잡도가 높아질수록 실패 가능성이 어떻게 달라지는지 학습한다. 
y = [0, 0, 0, 1, 1, 1]

# 로지스틱 회귀 모델 객체를 생성한다. 
# 아직 학습하지 않은 빈 모델을 준비하는 단계이다. 
# 이 시점에는 성공과 실패를 구분하는 규칙을 배우지 않았다. 
model = LogisticRegression()

# fit()은 모델을 학습시키는 메서드이다. 
# X = 작업 복잡도(입력)
# y = 실제 성공/실패 결과(정답)

# 두 데이터를 비교하여 작업 복잡도와 실패 확률 사이의 관계를 설명하는 모델의 계수와 절편을 학습한다.
# 예를 들어 복잡도 1~3은 성공했고 4~6은 실패했으므로 복잡도가 높을수록 실패 확률이 증가하는 관계를 학습한다.

# 단순히 "4이상이면 실패" 라는 if 문을 저장하는것이 아니다. 
# 로지스틱 회귀는 확률을 계산하는 수식을 학습한다. 
# 완료 B03: model을 X와 y로 학습하세요.
# 힌트: model.fit(입력, 정답)
model.fit(X,y)

# 학습이 끝난 모델에게 새롭계 예측할 작업을 전달한다. 
# [2] → 복잡도 2인 작업
# [5] → 복잡도 5인 작업
# 이 두 작업의 정답은 모델에게 새로 알려주지 않는다.
# 학습한 관계를 이용해서 결과를 예측하도록 한다.
# 2개의 샘플 * 1 개의 특징이므로 2차원 리스트를 사용한다.
new = [[2], [5]]

# model.classes_는 모델이 학습한 클래스의 종류와 순서를 보여준다. 
# 현재 y 에는 0과 1이  있으므로 [0,1]이 출력된다.
# 0 = 성공, 1 = 실패 
# 이 순서는 predict_proba() 의 확률 출력 순서를 해석할 때 중요하다. 
print("클래스 순서:", model.classes_)

# predict_proba()는 각 클래스의 속할 확률을 예측한다.
# predict()와의 차이: 
# predict_proba() 는 성공/실패 각각의 확률을 반환하고, predict()는 최종 예측 클래스(0 or 1)반환한다.

# new에는 작업이 2개 있으므로 결과도 2행으로 나온다. 
# 각 행의 첫 번째 값 → 성공(0) 확률
# 각 행의 두 번째 값 → 실패(1) 확률
#
# 예를 들어 [0.9, 0.1]이라면
# 성공 확률 90%, 실패 확률 10%라는 의미이다.
# .round(3)은 출력 숫자를 소수점 셋째 자리까지 반올림한다.
# 확률을 바꾸는 것이 아니라 표시 자릿수를 조정한다.
print("확률 [성공, 실패]:")
print(model.predict_proba(new).round(3))
# predict()는 각 작업의 최종 예측 클래스를 반환한다.
#
# 이진 분류에서 기본적으로 실패(1) 확률이 0.5를 넘으면
# 실패(1), 그렇지 않으면 성공(0)으로 예측한다.
#
# 복잡도 2 → 성공(0) 예측
# 복잡도 5 → 실패(1) 예측
#
# 즉 확률 자체가 아니라 최종 분류 결과만 출력한다.
print("예측 클래스:", model.predict(new))
# 이 작은 시연의 출력은 평가 점수가 아닙니다. 실제 성능 비교는 07번의 valid로 합니다.
