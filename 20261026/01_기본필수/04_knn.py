"""실습 04 기본필수: 이웃 3개의 투표와 평균을 비교합니다."""
# scikit-learn의 neighbors 모듈에서 KNN 알고리즘 두 가지를 가져온다.
#
# KNeighborsClassifier:
#   가장 가까운 K개 데이터의 정답을 비교해 다수결로 클래스를 결정하는 분류 모델이다.
#
# KNeighborsRegressor:
#   가장 가까운 K개 데이터의 숫자 정답을 이용해 평균값을 계산하는 회귀 모델이다.
#
# KNN = K-Nearest Neighbors (K-최근접 이웃)
# K는 참고할 이웃의 개수를 의미한다.
#
# 이번 문제에서는 K=3이므로 가장 가까운 3개를 참고한다.
from sklearn.neighbors import KNeighborsClassifier, KNeighborsRegressor

# X는 과거에 수집한 입력 데이터이다.
#
# 여기서는 숫자 하나가 하나의 특징(feature)을 의미한다.
# 예: 구매 금액, 작업 복잡도, 시험 점수 등
#
# 총 5개의 샘플이 있으며 각각 특징이 1개이므로 5행 × 1열의 2차원 리스트로 작성한다.
#
# X[0] = [1]
# X[1] = [2]
# X[2] = [4]
# X[3] = [7]
# X[4] = [9]
X = [[1], [2], [4], [7], [9]]

# 분류 모델에서 사용할 정답 데이터이다.
#
# 0 = 일반 구매
# 1 = 고액 구매
#
# 입력값 1 → 클래스 0
# 입력값 2 → 클래스 0
# 입력값 4 → 클래스 1
# 입력값 7 → 클래스 1
# 입력값 9 → 클래스 1
#
# KNN 분류는 새 데이터 주변의 정답들을 확인하여 가장 많이 등장하는 클래스를 선택한다.
class_y = [0, 0, 1, 1, 1]

# 회귀 모델에서 사용할 숫자 정답 데이터이다.
#
# X[0] = [1] → 정답 10
# X[1] = [2] → 정답 20
# X[2] = [4] → 정답 40
# X[3] = [7] → 정답 70
# X[4] = [9] → 정답 90
#
# 분류는 0과 1 중 하나를 선택하지만, 회귀는 이웃들의 숫자를 이용해 새로운 숫자를 예측한다.
number_y = [10, 20, 40, 70, 90]
# 3.2에 가까운 입력은 4, 2, 1입니다. 거리: 0.8, 1.2, 2.2



# -------------------------------------------------
# 1. KNN 분류 (Classifier)
# -------------------------------------------------

# KNN 분류 모델을 생성한다.
#
# n_neighbors=3:
# 새로운 데이터와 가장 가까운 과거 데이터 3개를 참고한다.
#
# 아직 학습 데이터를 전달하지 않았으므로 모델을 준비한 상태이다.
# 
# # 완료 B04a: 분류에서 이웃 수를 3으로 바꾸세요.
# 힌트: n_neighbors는 참고할 이웃 수입니다.
classifier = KNeighborsClassifier(n_neighbors=3)
# fit()으로 입력 X와 분류 정답 class_y를 모델에 전달한다.
#
# KNN은 선형회귀처럼 계수를 계산해 수식을 찾는 방식이 아니다.
# 과거 데이터와 정답을 저장해두고, 예측할 때 새로운 데이터와의 거리를 계산한다.
#
# 즉 KNN의 학습은 주로 비교할 데이터들을 기억하고 검색할 수 있도록 준비하는 과정이다.
classifier.fit(X, class_y)

# 복잡도 3.2인 새로운 데이터의 클래스를 예측한다.
#
# 3.2와 기존 데이터 사이의 거리를 계산한다.
#
# |3.2 - 1| = 2.2
# |3.2 - 2| = 1.2
# |3.2 - 4| = 0.8
# |3.2 - 7| = 3.8
# |3.2 - 9| = 5.8
#
# 가장 가까운 3개는 4, 2, 1이다.
#
# 이들의 클래스는 [1, 0, 0]이다.
# 0이 2개, 1이 1개이므로 다수결 결과는 0이다.
#
# 따라서 출력 결과는 [0]이다.
print("분류:", classifier.predict([[3.2]]))


# -------------------------------------------------
# 2. KNN 회귀 (Regressor)
# -------------------------------------------------

# KNN 회귀 모델을 생성한다.
#
# 분류와 마찬가지로 가까운 이웃 3개를 참고하지만
# 클래스를 투표로 결정하지 않고 숫자의 평균을 계산한다.
#
# 기본 설정에서는 이웃 3개를 동일한 비중으로 반영한다.
# 완료 B04b: 회귀에서도 이웃 수를 3으로 바꾸세요.
# 힌트: 같은 이웃의 숫자 정답 [40, 20, 10]을 평균냅니다.
regressor = KNeighborsRegressor(n_neighbors=3)

# X와 숫자 정답 number_y를 모델에 전달한다.
#
# 분류와 입력 X는 동일하지만 정답 y가 숫자이므로 회귀 예측을 수행할 수 있다.
#
# KNN 회귀 역시 데이터를 기억해두었다가 예측할 때 가까운 이웃의 정답을 활용한다.
regressor.fit(X, number_y)

# 입력값 3.2에 대한 숫자 결과를 예측한다.
#
# 가장 가까운 3개 입력값: [4, 2, 1]
# 해당하는 숫자 정답: [40, 20, 10]
#
# 회귀 결과 = (40 + 20 + 10) / 3
#          = 23.333333...
#
# round(2)는 소수점 둘째 자리까지 반올림한다.
#
# 따라서 출력 결과는 [23.33]이다.
print("회귀:", regressor.predict([[3.2]]).round(2))
