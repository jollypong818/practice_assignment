
"""실습 04: 랜덤 포레스트를 이용해 입력 특성별 중요도를 확인하는 예제"""

# ==================================================
# 1. 머신러닝 모델 가져오기
# ==================================================

# RandomForestClassifier는 여러 개의 의사결정나무(Decision Tree)를
# 만들어 예측 결과를 종합하는 앙상블(Ensemble) 분류 모델이다.
#
# 단일 의사결정나무보다 예측이 안정적일 수 있으며,
# 어떤 입력 특성이 예측에 중요하게 사용되었는지 확인할 수 있다.
from sklearn.ensemble import RandomForestClassifier


# ==================================================
# 2. 학습용 입력 데이터(X) 준비
# ==================================================

# 각 행은 하나의 요청 데이터를 의미한다.
# 각 행의 첫 번째 값은 글자 수, 두 번째 값은 허용 도구 수이다.
#
# 예: [100, 1]
# → 입력 글자 수가 100개이고 허용 도구 수가 1개인 요청
#
# 머신러닝 입력 X는 [샘플 수, 특성 수] 형태의 2차원 데이터다.
# 여기서는 샘플 6개, 특성 2개이므로 6행 2열이다.
X = [
    [100, 1],
    [200, 2],
    [300, 1],
    [700, 2],
    [800, 1],
    [900, 2]
]


# ==================================================
# 3. 정답 데이터(y) 준비
# ==================================================

# 각 요청의 실제 실패 여부를 나타낸다.
#
# 0 = 정상(성공)
# 1 = 실패
#
# X의 각 행과 y의 값은 순서대로 대응한다.
#
# 예:
# X[0] = [100, 1] → y[0] = 0
# X[3] = [700, 2] → y[3] = 1
y = [0, 0, 0, 1, 1, 1]


# ==================================================
# 4. 입력 특성 이름 정의
# ==================================================

# X의 각 열이 무엇을 의미하는지 이름을 지정한다.
#
# X의 첫 번째 열 → 글자 수
# X의 두 번째 열 → 허용 도구 수
#
# 나중에 중요도를 출력할 때 어떤 특성의 중요도인지
# 알아보기 쉽게 하기 위해 사용한다.
names = ["글자 수", "허용 도구 수"]


# ==================================================
# 5. 랜덤 포레스트 모델 생성
# ==================================================

# n_estimators=20
# → 의사결정나무를 20개 생성한다.
#
# max_depth=2
# → 각 의사결정나무의 최대 깊이를 2로 제한한다.
# → 나무가 지나치게 복잡해지는 것을 방지하기 위한 설정이다.
#
# random_state=42
# → 난수 생성 과정을 고정하여 실행 결과를 재현할 수 있게 한다.
#
# n_jobs=1
# → 계산에 사용할 작업 수를 1개로 설정한다.
# → n_jobs=-1이면 사용 가능한 CPU 코어를 병렬로 활용한다.
model = RandomForestClassifier(
    n_estimators=20,
    max_depth=2,
    random_state=42,
    n_jobs=1
)


# ==================================================
# 6. 모델 학습
# ==================================================

# fit(X, y)는 입력 데이터(X)와 정답(y)을 이용해
# 랜덤 포레스트 모델을 학습시키는 메서드다.
#
# 랜덤 포레스트는 여러 의사결정나무를 만들고,
# 각 나무가 데이터를 구분하는 조건을 학습한다.
#
# 예를 들어 글자 수가 특정 값보다 큰지 등을 기준으로
# 정상(0)과 실패(1)를 구분하는 규칙을 찾는다.
model.fit(X, y)


# ==================================================
# 7. 특성 중요도 확인 (TODO B04 정답)
# ==================================================

# feature_importances_는 학습된 랜덤 포레스트가
# 각 입력 특성에 부여한 중요도를 담고 있는 속성이다.
#
# 각 특성이 나무의 분기 과정에서 불순도(impurity)를
# 얼마나 감소시켰는지를 바탕으로 계산한다.
#
# 중요도는 일반적으로 0~1 사이의 값이며,
# 전체 특성 중요도의 합은 1이다.
#
# 예:
# [0.95, 0.05]
# → 글자 수 중요도: 0.95
# → 허용 도구 수 중요도: 0.05
#
# 실제 결과는 학습된 모델에 따라 결정된다.
importance = model.feature_importances_


# ==================================================
# 8. 특성 이름과 중요도를 함께 출력
# ==================================================

# zip()은 두 개 이상의 반복 가능한 데이터를
# 같은 순서끼리 묶어주는 파이썬 내장 함수다.
#
# names = ["글자 수", "허용 도구 수"]
# importance = [0.95, 0.05] 라고 가정하면
#
# zip(names, importance)는 다음처럼 묶는다.
# ("글자 수", 0.95)
# ("허용 도구 수", 0.05)
#
# for문은 묶인 데이터를 하나씩 꺼내 반복한다.
for name, value in zip(names, importance):

    # name : 특성 이름
    # value : 해당 특성의 중요도
    #
    # :.3f는 실수를 소수점 셋째 자리까지 출력한다.
    print(f"{name}: {value:.3f}")


# ==================================================
# 9. 특성 중요도 해석 시 주의사항
# ==================================================

# 특성 중요도가 높다는 것은 모델이 해당 특성을
# 예측 과정에서 많이 활용했다는 의미다.
#
# 하지만 중요도가 높다고 해서 그 특성이
# 실제 실패를 일으킨 원인이라고 단정할 수는 없다.
#
# 즉, 예측에 유용한 특성과 실제 원인은 구분해야 한다.
print("중요도가 높아도 실패의 원인이라고 단정하지 않습니다.")
