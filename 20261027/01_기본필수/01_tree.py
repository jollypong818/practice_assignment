"""실습 01: 입력을 질문으로 나누는 트리를 만듭니다. 
성능 평가가 아닌 Decision Tree의 기본 원리를 이해하기 위한 예제입니다.

목표:입력값 X를 보고 결과y가 0인지 1인지 분류하는 모델을 만듭니다.

현재 데이터에서는 100, 200, 300 --> 0
700, 800, 900 --> 1
이므로 Decision Tree는 "입력ㄱ밧이 어느 숫자보다 작은가/큰가?"
같은 기준을 찾아 데이터를 둘로 나누게 됩니다. 
"""

# 사이킷런에서 분류용 결정트리 모델을 가져옵니다. Classifier 는 값을 예측하는것이 아니라 0,1 같은 종류(클래스) 를 분류할때 사용하는 모델입니다. 
from sklearn.tree import DecisionTreeClassifier

# ---------------------------------------------------------
# 1. 학습 데이터 준비
# ---------------------------------------------------------
# X는 모델에게 입력으로 줄 데이터입니다.
#
# 머신러닝에서 X는 일반적으로 [샘플 수, 특성 수] 형태의 2차원 데이터를 사용합니다.
#
# 여기서는 샘플이 총 6개이고, 각 샘플마다 사용하는 특성(feature)은 숫자 하나뿐입니다.
#
# 예:
# [100] → 첫 번째 데이터
# [200] → 두 번째 데이터
#
# 따라서 X의 모양은 6개의 샘플 × 1개의 특성입니다.
X = [[100], [200], [300], [700], [800], [900]]

# y는 각 X에 대응하는 '정답'입니다.
#
# X와 y는 같은 위치끼리 연결됩니다.
#
# X      y
# 100 →  0 (성공)
# 200 →  0 (성공)
# 300 →  0 (성공)
# 700 →  1 (실패)
# 800 →  1 (실패)
# 900 →  1 (실패)
#
# 즉 모델에게 "이런 입력이 들어왔을 때 정답은 이것이야" 라고 알려주기 위한 학습용 정답입니다.
y = [0, 0, 0, 1, 1, 1]  # 같은 순서의 정답: 성공 0, 실패 1


# ---------------------------------------------------------
# 2. Decision Tree 모델 생성
# ---------------------------------------------------------
# DecisionTreeClassifier 객체를 생성합니다.
#
# 아직 여기서는 학습하지 않았습니다.
# 단순히 "이 설정으로 결정트리를 만들겠다"고 준비한 상태입니다.
#
# max_depth=1
# → 트리의 최대 깊이를 1로 제한합니다.
# → 질문(분기)을 한 번만 할 수 있습니다.
#
# 즉 대략 이런 형태만 만들 수 있습니다.
#
#             값 <= 기준?
#              /      \
#            0          1
#
# 이 예제에서는 결정트리가 어떻게 하나의 기준값으로
# 데이터를 나누는지 쉽게 보기 위해 깊이를 1로 제한합니다.
#
# random_state=42
# → 모델 내부에서 난수가 필요한 경우
#   실행할 때마다 결과가 달라지는 것을 막기 위한 설정입니다.
# → 42라는 숫자 자체에 특별한 의미는 없습니다.
model = DecisionTreeClassifier(max_depth=1, random_state=42)


# ---------------------------------------------------------
# 3. 모델 학습
# ---------------------------------------------------------
# fit(X, y)는 모델에게 데이터를 학습시키는 함수입니다.
#
# X = 입력 데이터
# y = 입력 데이터에 대응하는 정답
#
# 모델은 X와 y의 관계를 살펴보면서
# "어떤 숫자를 기준으로 나누면 0과 1을 가장 잘 구분할 수 있을까?" 를 찾습니다.
#
# 현재 데이터:
#
# 100 → 0
# 200 → 0
# 300 → 0
# 700 → 1
# 800 → 1
# 900 → 1
#
# 300과 700 사이에서 나누면 왼쪽은 모두 0, 오른쪽은 모두 1이 됩니다.
#
# 따라서 모델은 두 값의 중간인 500을 분기 기준으로 선택하게 됩니다.
model.fit(X, y)


# ---------------------------------------------------------
# 4. 새로운 데이터 예측
# ---------------------------------------------------------

# predict()는 학습이 끝난 모델에게
# 새로운 데이터의 결과를 예측시키는 함수입니다.
#
# 여기서는 250과 850을 넣어봅니다.
#
# 주의:
# 학습할 때 X가 [[100], [200], ...] 형태였기 때문에
# 예측할 때도 [[250], [850]]처럼 2차원 형태로 넣어야 합니다.
#
# 모델이 학습한 기준이 500이라면:
#
# 250 <= 500 → 0으로 예측
# 850 > 500  → 1로 예측
#
# predict()의 결과는 NumPy 배열로 반환됩니다.
prediction = model.predict([[250], [850]])


# ---------------------------------------------------------
# 5. 모델이 만든 분기 기준 확인
# ---------------------------------------------------------

# model.tree_에는 학습된 결정트리의 내부 구조가 들어 있습니다.
#
# threshold에는 각 노드에서 사용한 "분기 기준값"이 저장되어 있습니다.
#
# [0]은 첫 번째 노드(root node)의 기준값을 의미합니다.
#
# 이 데이터에서는 대략 500.0이 출력됩니다.
#
# 즉 모델이 학습한 질문은 사실상 "입력값 <= 500인가?" 입니다.
print("분기 기준:", model.tree_.threshold[0])

# ---------------------------------------------------------
# 6. 예측 결과 출력
# ---------------------------------------------------------

# prediction은 NumPy 배열입니다.
#
# 예:
# array([0, 1])
#
# .tolist()를 사용하면 일반 Python 리스트로 변환됩니다.
#
# [0, 1]
#
# 따라서 결과는
#
# 250 → 0
# 850 → 1
#
# 로 해석할 수 있습니다.
print("250·850 예측:", prediction.tolist())
