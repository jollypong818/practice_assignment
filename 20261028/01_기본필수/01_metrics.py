
"""
실습 01: 혼동행렬과 분류 모델 평가 지표

[학습 목표]
1. 실제 정답(y)과 모델 예측(pred)을 비교한다.
2. 혼동행렬(Confusion Matrix)을 이해한다.
3. Accuracy, Precision, Recall, F1-score를 계산한다.
4. 정확도가 높아도 좋은 모델이 아닐 수 있다는 점을 이해한다.

※ 이 실습에서는 모델을 직접 학습하지 않는다.
   이미 만들어진 예측 결과를 사용하여 평가 방법만 연습한다.
"""

# sklearn.metrics는 머신러닝 모델의 성능을 평가하는 도구 모음이다.
from sklearn.metrics import (
    confusion_matrix,  # 실제값과 예측값을 비교한 2×2 표
    accuracy_score,    # 전체 예측 중 맞힌 비율
    precision_score,   # 실패라고 예측한 것 중 실제 실패 비율
    recall_score,      # 실제 실패 중 모델이 발견한 비율
    f1_score           # 정밀도와 재현율의 조화평균
)


# ==========================================================
# 1. 실제 정답 데이터 (Ground Truth)
# ==========================================================

# 0 = 성공 (정상)
# 1 = 실패 (관심 대상, Positive Class)
#
# 여기서 1은 좋은 결과라는 의미가 아니다.
# 우리가 찾아내고 싶은 대상이 '실패'이므로 1로 정의한 것이다.
#
# [0]*14 → 0을 14개 생성
# [1]*6  → 1을 6개 생성
# +      → 두 리스트를 이어 붙인다.
#
# 전체 20건
# 실제 성공: 14건
# 실제 실패: 6건

y = [0]*14 + [1]*6


# ==========================================================
# 2. 모델의 예측 결과 (Prediction)
# ==========================================================

# 실제 모델이 예측했다고 가정한 결과이다.
#
# 앞의 14건은 실제 성공 데이터이다.
#   - 10건을 성공(0)으로 예측 → 정답
#   - 4건을 실패(1)로 예측 → 오답
#
# 뒤의 6건은 실제 실패 데이터이다.
#   - 4건을 성공(0)으로 예측 → 오답
#   - 2건을 실패(1)로 예측 → 정답
#
# y와 pred는 같은 인덱스끼리 비교한다.
# 예: y[0]과 pred[0]은 동일한 사건의 실제값과 예측값이다.

pred = [0]*10 + [1]*4 + [0]*4 + [1]*2


# ==========================================================
# 3. 혼동행렬 (Confusion Matrix)
# ==========================================================

# 혼동행렬은 모델이 어떤 유형의 정답과 오답을 냈는지 보여준다.
#
#                  예측 성공(0)   예측 실패(1)
# 실제 성공(0)       TN = 10       FP = 4
# 실제 실패(1)       FN = 4        TP = 2
#
# TN (True Negative)
#   실제 성공을 성공이라고 올바르게 예측
#
# FP (False Positive)
#   실제 성공인데 실패라고 잘못 예측 → 오탐
#
# FN (False Negative)
#   실제 실패인데 성공이라고 잘못 예측 → 미탐
#
# TP (True Positive)
#   실제 실패를 실패라고 올바르게 예측
#
# labels=[0, 1]
#   행과 열의 클래스 순서를 0, 1로 고정한다.
#   행 = 실제값, 열 = 예측값

print("혼동행렬(행 실제 / 열 예측, 성공0·실패1)")
print(confusion_matrix(y, pred, labels=[0, 1]))


# ==========================================================
# 4. Accuracy (정확도)
# ==========================================================

# 전체 데이터 중 예측을 올바르게 한 비율이다.
#
# 공식:
# Accuracy = (TP + TN) / (TP + TN + FP + FN)
#
# 계산:
# (2 + 10) / 20 = 0.6
#
# 전체 20건 중 12건을 맞혔으므로 정확도는 60%이다.
#
# 주의:
# 데이터가 불균형할 경우 정확도만으로 판단하면 위험하다.
# 예를 들어 실패가 1%, 성공이 99%인 데이터에서
# 모두 성공이라고 예측해도 정확도는 99%가 된다.

acc = accuracy_score(y, pred)


# ==========================================================
# 5. Precision (정밀도)
# ==========================================================

# 모델이 '실패'라고 예측한 것 중
# 실제로 실패한 비율을 나타낸다.
#
# 공식:
# Precision = TP / (TP + FP)
#
# 계산:
# 2 / (2 + 4) = 0.333...
#
# 모델이 실패라고 예측한 6건 중
# 실제 실패는 2건이므로 정밀도는 약 33.3%이다.
#
# 정밀도가 높다는 것은:
# 실패라고 판단했을 때 실제 실패일 가능성이 높다는 뜻이다.
#
# 활용:
# 정상 거래를 사기로 잘못 차단하는 일을 줄이고 싶을 때
# 정밀도를 중요하게 고려할 수 있다.
#
# zero_division=0:
# 분모가 0인 경우 오류나 경고 대신 0을 반환하도록 설정한다.
# 기본적으로 이진 분류에서 1을 관심 클래스로 평가한다.

precision = precision_score(y, pred, zero_division=0)


# ==========================================================
# 6. Recall (재현율)
# ==========================================================

# 실제 실패 데이터 중 모델이 실패를 찾아낸 비율이다.
#
# 공식:
# Recall = TP / (TP + FN)
#
# 계산:
# 2 / (2 + 4) = 0.333...
#
# 실제 실패 6건 중 2건만 발견했으므로
# 재현율은 약 33.3%이다.
#
# 재현율이 높다는 것은:
# 실제 실패를 놓치는 경우(FN)가 적다는 뜻이다.
#
# 활용:
# 불량품 탐지, 질병 선별 검사, 보안 침입 탐지 등
# 위험한 사건을 놓치지 않는 것이 중요할 때 사용한다.

recall = recall_score(y, pred, zero_division=0)


# ==========================================================
# 7. F1-score (F1 점수)
# ==========================================================

# Precision과 Recall을 함께 고려하는 평가 지표이다.
#
# 공식:
# F1 = 2 × (Precision × Recall) / (Precision + Recall)
#
# 계산:
# 2 × (0.333... × 0.333...) / (0.333... + 0.333...)
# = 0.333...
#
# 조화평균을 사용하기 때문에
# Precision과 Recall 중 하나가 매우 낮으면
# F1-score도 낮아지는 특징이 있다.
#
# 활용:
# 정밀도와 재현율을 모두 중요하게 평가할 때 사용한다.
# 특히 클래스 불균형이 있을 때 참고하기 좋다.
#
# 단, 모든 문제에서 F1이 가장 중요한 지표는 아니다.
# 실제 서비스에서는 FP와 FN의 비용도 고려해야 한다.

f1 = f1_score(y, pred, zero_division=0)


# ==========================================================
# 8. 최종 결과 출력
# ==========================================================

# f-string의 :.3f는 소수점 셋째 자리까지 출력한다.
# 예: 0.333333 → 0.333

print(
    f"Accuracy={acc:.3f}, "
    f"Precision={precision:.3f}, "
    f"Recall={recall:.3f}, "
    f"F1={f1:.3f}"
)

# 실제 실패 6건 중 2건만 찾아냈다는 뜻이다.
# 나머지 실패 4건은 성공이라고 잘못 예측했다.

print("실제 실패 6건 중 발견: 2건")
