"""실습 02: 값뿐 아니라 shape·dtype·device를 같이 확인합니다."""
import torch
# -------------------------------
# 1. 스칼라(Scalar)
# -------------------------------
# 숫자 하나만 들어 있는 0차원 Tensor
# 예: 딥러닝에서 loss(손실값)처럼 "숫자 하나"를 표현할 때 사용
scalar = torch.tensor(3.0)

# -------------------------------
# 2. 벡터(Vector)
# -------------------------------
# 숫자 여러 개가 한 줄로 들어 있는 1차원 Tensor
# shape은 (3,)
#
# 예:
# 한 상품의 특징이
# [가격, 무게, 판매량]
# 처럼 3개라면 이런 형태로 표현할 수 있음.
vector = torch.tensor([1.0, 2.0, 3.0])


# -------------------------------
# 3. 행렬(Matrix)
# -------------------------------
# 여러 개의 벡터를 묶은 2차원 Tensor
#
# [[1.0, 2.0],
#  [3.0, 4.0]]
#
# 행이 2개, 열이 2개이므로 shape은 (2, 2)
#
# ★ 원래 코드의
# torch.tensor([1.0, 2.0, 3.0, 4.0])
# 는 shape이 (4,)인 "1차원 벡터"임.
#
# dtype=torch.float32
# → 각 숫자를 32비트 실수로 저장
# → 딥러닝 모델에서 매우 흔하게 사용하는 자료형


# [[1.0, 2.0], [3.0, 4.0]]을 torch.float32의 2차원 Tensor matrix로 만드세요.
# 자료를 CPU로 옮기는 코드는 제공되어 있습니다.
# >>> B02
# 완료 B02: 위 요구사항을 읽고 이 블록을 완성하세요.
matrix = torch.tensor([[1.0, 2.0], [3.0, 4.0]], dtype=torch.float32)
# <<< B02


# -------------------------------
# 4. device
# -------------------------------
# Tensor가 어디에서 계산될지를 지정
#
# "cpu"  → CPU에서 계산
# "cuda" → NVIDIA GPU에서 계산
#
# PyTorch에서는 모델과 데이터가 같은 device에 있어야 함.
# 예를 들어 모델은 GPU에 있는데 데이터는 CPU에 있으면 오류가 날 수 있음.
matrix = matrix.to("cpu")

# -------------------------------
# 5. Tensor의 중요한 정보 확인
# -------------------------------

# shape
# → Tensor가 어떤 모양인지 확인
#
# dtype
# → Tensor 안의 숫자가 어떤 자료형인지 확인
#
# device
# → Tensor가 CPU/GPU 중 어디에 있는지 확인
print("스칼라:", tuple(scalar.shape), scalar.dtype, scalar.device)
print("벡터:", tuple(vector.shape), vector.dtype, vector.device)
print("행렬:", tuple(matrix.shape), matrix.dtype, matrix.device)

# Tensor 안에 실제로 어떤 값이 들어 있는지 확인
# .tolist()를 사용하면 일반 Python List 형태로 변환됨.
print("행렬 값:", matrix.tolist())


