"""실습 03: x=3에서 y=x²+2x+1과 기울기를 계산합니다."""
import torch


# -----------------------------------
# 1. 입력값 x 생성
# -----------------------------------
# x = 3.0인 0차원 Tensor(스칼라)를 생성
#
# requires_grad=True
# → PyTorch에게 "이 변수에 대한 미분값을 계산할 수 있도록
#    연산 과정을 추적해줘"라고 설정하는 것
#
# 딥러닝에서는 모델의 가중치(weight)를 학습할 때
# 기울기가 필요하기 때문에 이 기능을 사용함.
x = torch.tensor(3.0, requires_grad=True)


# -----------------------------------
# 2. Tensor 연산으로 함수 계산
# -----------------------------------
# 수학 함수:
# y = x² + 2x + 1
#
# x = 3을 대입하면
# y = 3² + 2×3 + 1
# y = 9 + 6 + 1 = 16
#
# x를 Python 숫자로 변환하면 안 되는 이유
# PyTorch가 Tensor 연산 과정을 추적해야
# 나중에 자동으로 미분할 수 있기 때문임.
#
# x ** 2 → x의 제곱
# 2 * x  → x에 2를 곱
# y = x² + 2x + 1을 Tensor 연산으로 작성하세요.
# x를 Python 숫자로 바꾸지 마세요. 계산 그래프가 이어져 있어야 합니다.
# >>> B03
# 완료 B03: 위 요구사항을 읽고 이 블록을 완성하세요.
y = x ** 2 + 2 * x + 1


# -----------------------------------
# 3. 자동 미분 실행
# -----------------------------------
# backward()는 역전파(Backpropagation)를 수행하는 함수
#
# y를 계산할 때 사용한 연산들을 거꾸로 따라가면서 x에 대한 y의 기울기(dy/dx)를 계산함.
#
# 수학적으로 직접 미분하면:
# y = x² + 2x + 1
# dy/dx = 2x + 2
#
# x = 3일 때:
# dy/dx = 2×3 + 2 = 8
#
# 계산된 기울기는 x.grad에 저장됨.
# 주의: backward()가 y의 값을 8로 바꾸는 것은 아님.
# <<< B03
# backward는 y 값을 바꾸지 않고 x.grad에 기울기를 계산합니다.
y.backward()

# -----------------------------------
# 4. 계산 결과 출력
# -----------------------------------
# y.item()
# → Tensor에 저장된 숫자 하나를 Python 숫자로 변환
# → 결과값은 16.0
print("y:", y.item())

# x.grad
# → x에 대한 y의 미분값이 저장된 Tensor
#
# x.grad.item()
# → 해당 Tensor에서 숫자만 추출
# → 결과값은 8.0
print("dy/dx:", x.grad.item())


