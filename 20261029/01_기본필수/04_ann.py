"""실습 04: 2 → 8 → 2 신경망의 순전파를 확인합니다."""

import torch
from torch import nn

# -----------------------------------
# 1. 난수 시드 고정
# -----------------------------------
# 신경망의 가중치(weight)는 처음에 무작위로 초기화됨.
#
# manual_seed(42)
# → 난수 생성 결과를 재현할 수 있도록 시드를 고정
# → 같은 환경에서 코드를 다시 실행했을 때 동일한 초기 가중치를 얻기 위한 목적
#
# 42라는 숫자 자체에 특별한 의미는 없음.
torch.manual_seed(42)


# -----------------------------------
# 2. 신경망 모델 정의
# -----------------------------------
# nn.Sequential()
# → 여러 신경망 계층(Layer)을 순서대로 연결하는 기능
#
# 전체 구조:
# 입력층(2개 특징) → 은닉층(8개 뉴런) → 출력층(2개 점수)
#
# nn.Linear(2, 8)
# → 입력 특징 2개를 받아 출력 특징 8개로 변환
# → 가중치와 편향을 이용한 선형 변환
# → y = Wx + b
#
# nn.ReLU()
# → 활성화 함수(Activation Function)
# → 음수는 0으로, 양수는 그대로 출력
# → 신경망이 비선형 관계를 학습할 수 있도록 함
#
# nn.Linear(8, 2)
# → 은닉층에서 나온 8개 값을 받아
#   최종적으로 2개의 출력 점수를 생성
#
#  기존 nn.Linear(8, 1)을
#   nn.Linear(8, 2)로 수정하는 것이 이번 과제!
model = nn.Sequential(
    nn.Linear(2, 8),
    nn.ReLU(),
    nn.Linear(8, 2)
)


# -----------------------------------
# 3. 입력 데이터 생성
# -----------------------------------
# 총 4개의 샘플이 존재
# 각 샘플은 2개의 특징(feature)을 가짐.
#
# [1.0, 2.0] → 첫 번째 샘플
# [3.0, 4.0] → 두 번째 샘플
# [0.0, 1.0] → 세 번째 샘플
# [2.0, 0.0] → 네 번째 샘플
#
# 따라서 X.shape = (4, 2)
# → 샘플 4개 × 특징 2개
X = torch.tensor([
    [1.0, 2.0],
    [3.0, 4.0],
    [0.0, 1.0],
    [2.0, 0.0]
])


# -----------------------------------
# 4. 순전파(Forward Propagation)
# -----------------------------------
# model(X)
# → 입력 데이터 X를 신경망에 통과시킴.
#
# 내부적으로:
# (4, 2) → Linear → (4, 8)
# (4, 8) → ReLU   → (4, 8)
# (4, 8) → Linear → (4, 2)
#
# 최종 출력 logits의 shape은 (4, 2)
#
# logits
# → 모델이 계산한 원시 점수(raw score) → 아직 확률로 변환한 값은 아님.
logits = model(X)


# -----------------------------------
# 5. 입력 및 출력 형태 확인
# -----------------------------------
# X.shape
# → 입력 샘플 수와 특징 수 확인
print("입력:", tuple(X.shape))

# logits.shape
# → 출력 샘플 수와 클래스별 점수 개수 확인
print("출력:", tuple(logits.shape))


# -----------------------------------
# 6. 학습 가능한 파라미터 개수 확인
# -----------------------------------
# model.parameters()
# → 모델이 가지고 있는 가중치와 편향을 가져옴.
#
# p.numel()
# → 해당 Tensor에 포함된 숫자의 총개수
#
# sum(...)
# → 모든 계층의 파라미터 개수를 합산
#
# 첫 번째 Linear(2, 8)
# → 가중치 2×8 = 16개
# → 편향 8개
# → 총 24개
#
# 두 번째 Linear(8, 2)
# → 가중치 8×2 = 16개
# → 편향 2개
# → 총 18개
#
# 전체 파라미터 = 24 + 18 = 42개
print("파라미터 수:", sum(p.numel() for p in model.parameters()))


# -----------------------------------
